declare(strict_types=1);

namespace Polkurier\Shipping\Block\Adminhtml\Shipment;

use Magento\Backend\Block\Template;
use Magento\Framework\Registry;
use Polkurier\Shipping\Model\PolkurierCarrier;

class Form extends Template
{
    public function __construct(
        private readonly Registry $registry,
        Template\Context $context,
        array $data = []
    ) {
        parent::__construct($context, $data);
    }

    public function getOrder()
    {
        $shipment = $this->registry->registry('current_shipment');

        return $shipment ? $shipment->getOrder() : null;
    }

    public function isTargetCarrier(): bool
    {
        $order = $this->getOrder();
        if (!$order) {
            return false;
        }

        return $order->getShippingMethod(true)->getCarrierCode() === PolkurierCarrier::CODE;
    }

    protected function _toHtml()
    {
        return parent::_toHtml(); // TODO: Change the autogenerated stub
    }
}
